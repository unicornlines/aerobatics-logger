#!/usr/bin/env python3
"""Turn the brand SVG into a printable OpenSCAD polygon: case/art/logo.scad.

    python3 case/tools/mklogo_scad.py [diameter_mm=18] [min_line_mm=0.45]

FDM cannot print the silkscreen version (0.16 mm lines). This one is traced at the size it is
printed and every stroke is thickened to at least min_line_mm (about one nozzle width), so the
inlay comes out clean. The output is committed; OpenSCAD never reads the SVG.
Needs: cairosvg, numpy, opencv-python-headless.
"""
import io
import sys
from pathlib import Path

import cairosvg
import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "hardware" / "art" / "unicornlines-logo.svg"
OUT = ROOT / "case" / "art" / "logo.scad"
PX = 40  # pixels per mm


def main():
    size = float(sys.argv[1]) if len(sys.argv) > 1 else 18.0
    min_line = float(sys.argv[2]) if len(sys.argv) > 2 else 0.45
    png = cairosvg.svg2png(url=str(SVG), output_width=int(size * PX * 1.3), background_color="white")
    im = np.array(Image.open(io.BytesIO(png)).convert("L"))
    ink = (im < 128).astype(np.uint8)
    ys, xs = np.nonzero(ink)
    ink = ink[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    s = size * PX / max(ink.shape)
    ink = cv2.resize(ink, (round(ink.shape[1] * s), round(ink.shape[0] * s)), interpolation=cv2.INTER_AREA)
    ink = (ink > 0).astype(np.uint8)
    # thicken strokes thinner than min_line: add the thin parts back, dilated
    k = max(1, int(round(min_line * PX)))
    ker = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k))
    opened = cv2.morphologyEx(ink, cv2.MORPH_OPEN, ker)
    thin = cv2.subtract(ink, opened)
    ink = cv2.bitwise_or(ink, cv2.dilate(thin, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k // 2 + 1, k // 2 + 1))))
    # gaps narrower than min_line close up when printed: close them
    ink = cv2.morphologyEx(ink, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k // 3 + 1, k // 3 + 1)))
    contours, _ = cv2.findContours(ink, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
    h, w = ink.shape
    pts, paths = [], []
    for c in contours:
        c = cv2.approxPolyDP(c, 0.02 * PX, True)
        if len(c) < 3 or cv2.contourArea(c) < (0.2 * PX) ** 2:
            continue
        path = []
        for p in c[:, 0, :]:
            path.append(len(pts))
            pts.append(((p[0] - w / 2) / PX, (h / 2 - p[1]) / PX))
        paths.append(path)
    OUT.parent.mkdir(exist_ok=True)
    with OUT.open("w") as f:
        f.write(f"// GENERATED by case/tools/mklogo_scad.py from hardware/art/unicornlines-logo.svg\n"
                f"// {w / PX:.2f} x {h / PX:.2f} mm, strokes >= {min_line} mm, centred. Holes are even-odd paths.\n")
        f.write(f"logo_size = [{w / PX:.3f}, {h / PX:.3f}];\n")
        f.write("module logo_art() polygon(points = [" + ",".join(f"[{x:.3f},{y:.3f}]" for x, y in pts) + "],\n  paths = ["
                + ",".join("[" + ",".join(map(str, p)) + "]" for p in paths) + "]);\n")
    print(f"{OUT.relative_to(ROOT)}: {len(paths)} paths, {len(pts)} points, {w / PX:.1f} x {h / PX:.1f} mm")


if __name__ == "__main__":
    main()
