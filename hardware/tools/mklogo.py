"""Turn an SVG logo into a silkscreen footprint for ../kicad/logger.pretty.

    python3 mklogo.py ../art/unicornlines-logo.svg Unicornlines_Logo 13.0

The SVG is rasterised (cairosvg), thin strokes are thickened to the silkscreen minimum, the outline
is traced (OpenCV) and written as filled polygons on F.SilkS (holes fractured, as KiCad needs).
Needs: cairosvg, numpy, opencv-python-headless, KiCad 7 Python. The footprint is committed, so
pcb.py doesn't need any of this.
"""
import io, os, sys
import numpy as np
import cairosvg, cv2
from PIL import Image
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.join(HERE, "..", "kicad", "logger.pretty")
PX_PER_MM = 80
MIN_LINE_MM = 0.16          # silkscreen minimum line width at most fabs is 0.15 mm


def main():
    src, name, width_mm = sys.argv[1], sys.argv[2], float(sys.argv[3])
    png = cairosvg.svg2png(url=src, output_width=int(width_mm * PX_PER_MM * 1.25), background_color="white")
    im = np.array(Image.open(io.BytesIO(png)).convert("L"))
    ink = (im < 128).astype(np.uint8)
    ys, xs = np.nonzero(ink)
    ink = ink[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    scale = width_mm * PX_PER_MM / ink.shape[1]
    ink = cv2.resize(ink, (int(ink.shape[1] * scale), int(ink.shape[0] * scale)), interpolation=cv2.INTER_NEAREST)
    # thicken strokes thinner than the silk minimum: whatever a disc of that width can't fit in grows
    d = int(round(MIN_LINE_MM * PX_PER_MM)) | 1
    disc = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (d, d))
    thin = cv2.subtract(ink, cv2.morphologyEx(ink, cv2.MORPH_OPEN, disc))
    ink = cv2.bitwise_or(ink, cv2.dilate(thin, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (d // 2 | 1,) * 2)))
    contours, hier = cv2.findContours(ink, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    h, w = ink.shape
    to_nm = lambda p: pcbnew.VECTOR2I(pcbnew.FromMM(float(p[0] - w / 2) / PX_PER_MM), pcbnew.FromMM(float(p[1] - h / 2) / PX_PER_MM))

    board = pcbnew.BOARD()
    fp = pcbnew.FOOTPRINT(board)
    fp.SetFPID(pcbnew.LIB_ID("logger", name))
    fp.SetAttributes(pcbnew.FP_BOARD_ONLY | pcbnew.FP_EXCLUDE_FROM_BOM | pcbnew.FP_EXCLUDE_FROM_POS_FILES)
    fp.SetReference("LOGO"); fp.Reference().SetVisible(False); fp.Reference().SetLayer(pcbnew.F_Fab)
    fp.SetValue(name); fp.Value().SetVisible(False); fp.Value().SetLayer(pcbnew.F_Fab)
    fp.SetDescription(f"{name}, {width_mm:g} mm wide, silkscreen; generated by tools/mklogo.py")
    n = 0
    for i, c in enumerate(contours):
        if hier[0][i][3] != -1 or cv2.contourArea(c) < 4:
            continue                       # holes are handled with their outer contour
        ps = pcbnew.SHAPE_POLY_SET()
        approx = cv2.approxPolyDP(c, 0.6, True)[:, 0, :]
        ps.NewOutline()
        for p in approx:
            ps.Append(to_nm(p))
        j = hier[0][i][2]
        while j != -1:
            hole = cv2.approxPolyDP(contours[j], 0.6, True)[:, 0, :]
            if len(hole) >= 3:
                hi = ps.NewHole()
                for p in hole:
                    ps.Append(to_nm(p), 0, hi)
            j = hier[0][j][0]
        ps.Fracture(pcbnew.SHAPE_POLY_SET.PM_FAST)
        for k in range(ps.OutlineCount()):
            s = pcbnew.FP_SHAPE(fp)
            s.SetShape(pcbnew.SHAPE_T_POLY); s.SetFilled(True); s.SetWidth(0); s.SetLayer(pcbnew.F_SilkS)
            sub = pcbnew.SHAPE_POLY_SET(); sub.AddOutline(ps.Outline(k))
            s.SetPolyShape(sub)
            fp.Add(s); n += 1
    pcbnew.FootprintSave(LIB, fp)
    print(f"wrote {name}: {n} polygons, {w / PX_PER_MM:.1f} x {h / PX_PER_MM:.1f} mm")


if __name__ == "__main__":
    main()
